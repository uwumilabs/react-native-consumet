#!/usr/bin/env node
/**
 * Writes apps/src/registry/local-dist-map.ts: the code the Registry tab runs in its "Local dist"
 * mode instead of fetching `main`. It holds each registry bundle once, keyed by the `distFile` of
 * the entries built into it (extensions and extractors). The app still checks the code against
 * the entry's `sha256`, so a stale map shows up as an integrity mismatch.
 *
 * scripts/prepare-registry.js writes it after publishing, so `yarn build:registry` and the
 * pre-commit hook keep it current, and `yarn registry:check` reports it when it is out of date.
 * To write it on its own, from the current registry and dist/:
 *   yarn example gen:local-dist
 */
const fs = require('fs');
const path = require('path');
const { repoRoot, readRegistry, registryLayout } = require('../../scripts/registry-paths');

/** The generated file, relative to the repo root. */
const LOCAL_DIST_MAP_FILE = 'apps/src/registry/local-dist-map.ts';

/** The map's source for `registry`, with the bundles under `root`. Throws when a bundle is missing. */
function renderLocalDistMap(registry, root = repoRoot) {
  const { entriesOf, entryKey } = registryLayout(root);
  const bundles = new Map();
  for (const { kind, entry } of entriesOf(registry)) {
    const label = entryKey(kind, entry);
    const file = entry.distFile && path.join(root, entry.distFile);
    if (!file || !fs.existsSync(file)) {
      throw new Error(`${label}: no build output at ${entry.distFile} (run yarn build)`);
    }
    const bundle = bundles.get(entry.distFile) || { code: fs.readFileSync(file, 'utf8'), labels: [] };
    bundle.labels.push(label);
    bundles.set(entry.distFile, bundle);
  }

  const lines = [
    '// Generated by apps/scripts/generate-local-dist.js from src/extension-registry.json and dist/;',
    '// do not edit. scripts/prepare-registry.js rewrites it (yarn build:registry, the pre-commit hook).',
    '',
    '/** This file, relative to the repo root. */',
    `export const LOCAL_DIST_FILE = ${JSON.stringify(LOCAL_DIST_MAP_FILE)};`,
    '',
    '/** The code of each registry bundle, keyed by the `distFile` of the entries built into it. */',
    'const LOCAL_DIST_MAP: Record<string, string> = {',
    ...[...bundles].flatMap(([distFile, { code, labels }]) => [
      `  // ${labels.join(', ')}`,
      `  ${JSON.stringify(distFile)}: ${JSON.stringify(code)},`,
    ]),
    '};',
    '',
    'export default LOCAL_DIST_MAP;',
    '',
  ];
  return { source: lines.join('\n'), bundles: bundles.size };
}

const readMap = (root) => {
  const file = path.join(root, LOCAL_DIST_MAP_FILE);
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : undefined;
};

/** Whether the map under `root` is what `registry` and dist/ give. Throws when a bundle is missing. */
function isLocalDistMapCurrent(registry, root = repoRoot) {
  return readMap(root) === renderLocalDistMap(registry, root).source;
}

/** Writes the map for `registry` under `root`; returns how many bundles it holds and whether it changed. */
function writeLocalDistMap(registry, root = repoRoot) {
  const { source, bundles } = renderLocalDistMap(registry, root);
  const changed = readMap(root) !== source;
  if (changed) {
    fs.mkdirSync(path.dirname(path.join(root, LOCAL_DIST_MAP_FILE)), { recursive: true });
    fs.writeFileSync(path.join(root, LOCAL_DIST_MAP_FILE), source);
  }
  return { bundles, changed };
}

module.exports = { LOCAL_DIST_MAP_FILE, isLocalDistMapCurrent, writeLocalDistMap };

if (require.main === module) {
  try {
    const { bundles, changed } = writeLocalDistMap(readRegistry());
    console.log(`${changed ? 'wrote' : 'unchanged:'} ${LOCAL_DIST_MAP_FILE} (${bundles} bundles)`);
  } catch (error) {
    console.error(`generate-local-dist: ${error.message}`);
    process.exit(1);
  }
}
